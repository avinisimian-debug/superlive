"""Writes src/lib/branch-verification.generated.ts from verified.json."""
import json, sys
from common import W
v=json.load(open(W+"verified.json"))
out=sys.argv[1]
def js(x): return json.dumps(x,ensure_ascii=False,separators=(",",":"))
loc=[]; hrs=[]
for rid in sorted(v):
    r=v[rid]
    if r["loc"]:
        loc.append(f'  "{rid}":[{round(r["lat"],7)},{round(r["lng"],7)},"{r["loc"]}",{js(r["city"])},{js(r["name"])}],')
    if r["hours"] and r["loc"]:
        hrs.append(f'  "{rid}":["{r["hoursSrc"]}",{js(r["hoursUrl"])},{js(r["hours"])}],')
src=f'''// AUTO-GENERATED by scripts/branch-verification (see README there). Do not edit by hand.
// Sources: OpenStreetMap (© OpenStreetMap contributors, ODbL), chain store locators, Nominatim.
import type {{ RawSlot }} from "./schedules";
import type {{ HoursSource, LocationSource }} from "./types";

/** Date the sources were fetched and cross-checked. */
export const VERIFIED_ON = "2026-10-21";

/**
 * Branches whose pin was confirmed by an independent source:
 * id -> [lat, lng, source, settlement (or null to keep), corrected name (or null to keep)].
 */
export const LOCATION_CHECKS: Record<string, [number, number, LocationSource, string | null, string | null]> = {{
{chr(10).join(loc)}
}};

/** Published opening hours: id -> [source, source page, days (0 = Sunday)]. */
export const BRANCH_HOURS: Record<string, [HoursSource, string, (RawSlot[] | null)[]]> = {{
{chr(10).join(hrs)}
}};
'''
open(out,"w").write(src); print(len(loc),len(hrs))
